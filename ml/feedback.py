"""Оценка ответа ассистента: кнопки под последним ответом и реакция системы на них.

Оценка одна на чат и не привязана к конкретному сообщению (`chats.rating`,
см. storage.set_chat_rating). Пока оценка не поставлена, под последним ответом
ассистента висят две кнопки-«клавиатуры»:

* «Спасибо за помощь» — от пользователя уходит это сообщение, система без LLM
  отвечает захардкоженным текстом (`POSITIVE_REPLY`), в чат пишется positive.
  Под этой благодарностью кнопок оценки нет (см. `is_service_reply`): это
  подтверждение, а не ответ на вопрос.
* «Ответ мне не подходит» — уходит это сообщение, система без LLM отвечает
  `NEGATIVE_REPLY`, а под ответом появляется набор причин (`REASONS`) и кнопка
  «Позови оператора». Выбор причины и оператор — это уже обычный ход с LLM:
  модель либо перегенерирует ответ с учётом замечания, либо решает вопрос перевода.

Тексты причин уходят в БД как сообщения пользователя, поэтому они же служат
валидным значением `reason`. Подсказки для LLM (`reason_hint`, `operator_hint`)
не сохраняются в чате — они дописываются к вопросу только на время хода.
"""

from __future__ import annotations

POSITIVE_LABEL = "Спасибо за помощь"
NEGATIVE_LABEL = "Ответ мне не подходит"
OPERATOR_LABEL = "Позови оператора"

# Причины, по которым ответ может не подойти. Это и кнопки, и допустимые значения
# reason: строки уходят в чат как сообщение пользователя.
REASONS = (
    "Слишком кратко",
    "Не по теме вопроса",
    "Нет нужной информации",
    "Непонятно написано",
)

POSITIVE_REPLY = (
    "Рад был помочь! Если появятся ещё вопросы по Порталу поставщиков — пишите."
)

NEGATIVE_REPLY = (
    "Жаль, что ответ не подошёл. Напишите, что именно не так, — я переработаю ответ. "
    "Если нужен человек, позовите оператора."
)


def is_reason(value: str | None) -> bool:
    """Является ли значение одной из причин из REASONS."""
    return bool(value) and value in REASONS


def is_service_reply(text: str | None) -> bool:
    """Служебная реплика системы, под которой не нужны кнопки оценки.

    Такая одна — благодарность после кнопки «Спасибо за помощь» (`POSITIVE_REPLY`):
    это подтверждение, а не ответ на вопрос, оценивать в нём нечего.
    """
    return (text or "").strip() == POSITIVE_REPLY


def reason_hint(reason: str) -> str:
    """Подсказка LLM на ход с выбранной причиной: перегенерировать ответ на исходный вопрос."""
    return (
        f"[Оценка ответа] Пользователь отметил, что предыдущий ответ ему не подошёл: «{reason}». "
        "Нового вопроса он не задавал: последнее сообщение — это замечание к уже данному ответу. "
        "Перегенерируй ответ на исходный вопрос пользователя с учётом замечания: исправь именно то, "
        "на что он жалуется. Не отвечай на текст замечания как на отдельный вопрос."
    )


def operator_hint() -> str:
    """Подсказка LLM на кнопку «Позови оператора»: решить, нужен ли перевод на линию."""
    return (
        "[Запрос оператора] Пользователь просит позвать оператора. Оцени, нужно ли переводить "
        "обращение на линию поддержки. Если по инструкциям можно ответить — сначала ответь, "
        "а оператора подключай только тогда, когда ответа в базе знаний действительно нет: "
        "тогда вызови transfer_to_support и сообщи, что вопрос передан специалисту."
    )


